#!/usr/bin/env python3
"""Generate the bounded runtime reference from the user's exact ARM64 ELF."""
import argparse
import hashlib
import struct
from pathlib import Path

EXPECTED_SHA256 = '549093d79212873f26bc13f8957d06cc7575e92f24b53721eb13e8a0a53cb657'


def generate(source, destination):
    data = Path(source).read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError('ELF SHA-256 does not match the inspected APK library')
    if data[:7] != b'\x7fELF\x02\x01\x01' or struct.unpack_from('<HH', data, 16) != (3, 183):
        raise ValueError('Expected AArch64 ELF64 little-endian ET_DYN')
    phoff = struct.unpack_from('<Q', data, 32)[0]
    stride, count = struct.unpack_from('<HH', data, 54)
    if stride != 56 or count > 32 or phoff + stride * count > len(data):
        raise ValueError('Invalid program-header bounds')
    loads, notes = [], []
    for index in range(count):
        kind, flags, offset, va, _, filesz, memsz, align = struct.unpack_from('<II6Q', data, phoff + stride * index)
        if kind in (1, 4) and offset + filesz > len(data):
            raise ValueError('Segment exceeds file')
        if kind == 1:
            if filesz > memsz or not align or align & (align - 1) or offset % align != va % align:
                raise ValueError('Invalid PT_LOAD')
            loads.append((offset, va, filesz, memsz, flags))
        if kind == 4:
            notes.append((offset, va, filesz))
    if not loads or loads[0][0] != 0 or loads[0][1] != 0:
        raise ValueError('This reference requires a zero-based first segment')
    samples, build_id = [], None
    for offset, va, size in notes:
        cursor = 0
        while cursor + 12 <= size:
            namesz, descsz, kind = struct.unpack_from('<III', data, offset + cursor)
            name_at = cursor + 12
            desc_at = name_at + ((namesz + 3) & ~3)
            end = desc_at + ((descsz + 3) & ~3)
            if end > size or end <= cursor:
                raise ValueError('Invalid ELF note')
            if kind == 3 and data[offset + name_at:offset + name_at + namesz] == b'GNU\0':
                if build_id is not None:
                    raise ValueError('Ambiguous build ID')
                build_id = data[offset + desc_at:offset + desc_at + descsz].hex()
                samples.append(('GNU_BUILD_ID', va + cursor, data[offset + cursor:offset + end].hex()))
            cursor = end
    if build_id != 'ee8bf32c4483429084fde022704ead01a94b6620':
        raise ValueError('Unexpected build ID')
    executable = next(segment for segment in loads if segment[4] & 1)
    for index, delta in enumerate((0, 4096, 8192)):
        offset, va, filesz, _, _ = executable
        if delta + 64 > filesz:
            raise ValueError('Anchor exceeds executable segment')
        samples.append(('CODE_' + str(index), va + delta, data[offset + delta:offset + delta + 64].hex()))
    lines = [
        '// Generated by Build-ModuleReference.py from the exact SHA-256-verified ELF.',
        'namespace HeadBridge.Mapping {',
        '    internal static class ApkModule {',
        '        internal const string FileSha256 = "' + EXPECTED_SHA256 + '";',
        '        internal const string BuildId = "' + build_id + '";',
        '        internal const ulong FileSize = ' + str(len(data)) + 'UL;',
        '        internal const ulong ProgramOffset = ' + str(phoff) + 'UL;',
        '        internal const string HeaderHex = "' + data[:64].hex() + '";',
        '        internal const string ProgramsHex = "' + data[phoff:phoff + count * stride].hex() + '";',
        '        internal static readonly ModuleSegment[] Segments = new ModuleSegment[] {',
    ]
    for offset, va, filesz, memsz, flags in loads:
        lines.append('            new ModuleSegment(0x%xUL, 0x%xUL, 0x%xUL, 0x%xUL, %d),' % (offset, va, filesz, memsz, flags))
    lines += ['        };', '        internal static readonly ModuleSample[] Samples = new ModuleSample[] {']
    for name, va, value in samples:
        lines.append('            new ModuleSample("%s", 0x%xUL, "%s"),' % (name, va, value))
    lines += ['        };', '    }', '}', '']
    Path(destination).write_text('\n'.join(lines), encoding='utf-8')
    print('ModuleReference=PASS PT_LOADs=%d Samples=%d BuildId=%s' % (len(loads), len(samples), build_id))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('elf')
    parser.add_argument('output')
    args = parser.parse_args()
    generate(args.elf, args.output)
